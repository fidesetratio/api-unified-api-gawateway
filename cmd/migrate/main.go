// Command migrate creates the database (if missing) and applies every SQL
// migration, reading the connection from .env (DB_HOST, DB_PORT, DB_USER,
// DB_PASSWORD, DB_NAME).
package main

import (
	"context"
	"fmt"
	"io/fs"
	"os"
	"os/signal"
	"path/filepath"
	"sort"
	"strings"
	"syscall"

	"unifiedgw/internal/config"
	"unifiedgw/internal/store"
	"unifiedgw/migrations"
)

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	if err := run(ctx); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		stop()
		os.Exit(1)
	}
}

// dumpSQL prints every migration as one script (no database needed), for
// running by hand with psql. It also records the versions so that a later
// migrate run does not apply them again.
func dumpSQL() error {
	files, err := fs.Glob(migrations.FS, "*.sql")
	if err != nil {
		return err
	}
	sort.Strings(files)
	fmt.Println("-- Generated by: migrate -sql. Run against an empty database, e.g.")
	fmt.Println("--   createdb gateway_dev && psql -v ON_ERROR_STOP=1 -1 -d gateway_dev -f schema.sql")
	fmt.Println("CREATE TABLE IF NOT EXISTS schema_migrations (")
	fmt.Println("  version text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now());")
	for _, f := range files {
		body, err := fs.ReadFile(migrations.FS, f)
		if err != nil {
			return err
		}
		v := strings.TrimSuffix(f, ".sql")
		fmt.Printf("\n-- ==== %s ====\n%s\nINSERT INTO schema_migrations (version) VALUES ('%s');\n", f, strings.TrimSpace(string(body)), v)
	}
	return nil
}

func run(ctx context.Context) error {
	if len(os.Args) > 1 && os.Args[1] == "-sql" {
		return dumpSQL()
	}
	dir, err := config.LoadDefaultDotenv()
	if err != nil {
		return err
	}
	getenv, err := config.WithDefaults(os.Getenv, filepath.Join(dir, config.DefaultKeyFile))
	if err != nil {
		return err
	}
	url := getenv("GATEWAY_DATABASE_URL")

	if err := store.EnsureDatabase(ctx, url); err != nil {
		return err
	}
	pool, err := store.Open(ctx, url)
	if err != nil {
		return err
	}
	defer pool.Close()

	applied, err := store.Migrate(ctx, pool, migrations.FS)
	if err != nil {
		return err
	}
	if len(applied) == 0 {
		fmt.Println("database is up to date")
		return nil
	}
	for _, v := range applied {
		fmt.Println("applied", v)
	}
	return nil
}
